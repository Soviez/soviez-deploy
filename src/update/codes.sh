soviez_rand_hex() {
  local n="${1:-4}"
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex "$n" | head -c $((n * 2))
    return 0
  fi
  python3 -c "import secrets; print(secrets.token_hex(int('$n')))"
}

