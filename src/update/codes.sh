soviez_update_die() {
  local code="${1:-UPDATE_RECOVERY_REQUIRED}" message="${2:-Update failed}"
  soviez_log_error "${code}: ${message}"
  SOVIEZ_UPD_CODE="$code" SOVIEZ_UPD_MSG="$(soviez_redact_text "$message")" python3 - <<'PY' >&2
import json, os
print(json.dumps({"ok": False, "code": os.environ["SOVIEZ_UPD_CODE"],
                  "message": os.environ["SOVIEZ_UPD_MSG"]}, separators=(",", ":")))
PY
  exit "$SOVIEZ_ERR_UPDATE"
}

soviez_update_ok() {
  local code="${1:-OK}" message="${2:-OK}"
  SOVIEZ_UPD_CODE="$code" SOVIEZ_UPD_MSG="$(soviez_redact_text "$message")" python3 - <<'PY'
import json, os
print(json.dumps({"ok": True, "code": os.environ["SOVIEZ_UPD_CODE"],
                  "message": os.environ["SOVIEZ_UPD_MSG"]}, separators=(",", ":")))
PY
}
