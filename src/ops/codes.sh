soviez_ops_die() {
  local code="${1:-OPERATION_STATE_CORRUPT}" message="${2:-Operation failed}"
  soviez_log_error "${code}: ${message}"
  SOVIEZ_OPS_CODE="$code" SOVIEZ_OPS_MESSAGE="$(soviez_redact_text "$message")" python3 - <<'PY' >&2
import json, os
print(json.dumps({"ok": False, "code": os.environ["SOVIEZ_OPS_CODE"],
                  "message": os.environ["SOVIEZ_OPS_MESSAGE"]}, separators=(",", ":")))
PY
  exit "$SOVIEZ_ERR_OPS"
}

soviez_ops_ok() {
  local code="${1:-OK}" message="${2:-OK}"
  SOVIEZ_OPS_CODE="$code" SOVIEZ_OPS_MESSAGE="$(soviez_redact_text "$message")" python3 - <<'PY'
import json, os
print(json.dumps({"ok": True, "code": os.environ["SOVIEZ_OPS_CODE"],
                  "message": os.environ["SOVIEZ_OPS_MESSAGE"]}, separators=(",", ":")))
PY
}
