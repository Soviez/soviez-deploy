  OPERATION_LOCK_CONFLICT
  OPERATION_LOCK_STALE
  OPERATION_LOCK_RECOVERY_REQUIRED
  OPERATION_LOCK_IDENTITY_MISMATCH
  OPERATION_DEADLOCK_PREVENTED
  OPERATION_WORKER_MISSING
  OPERATION_WORKER_DUPLICATE
  OPERATION_WORKER_IDENTITY_MISMATCH
  OPERATION_HEARTBEAT_STALE
  OPERATION_SYSTEMD_UNIT_MISSING
  OPERATION_SYSTEMD_STATE_MISMATCH
  OPERATION_REATTACH_UNAVAILABLE
  OPERATION_CANCEL_ACCEPTED
