soviez_ssl_die() {
  local code="$1"
  local msg="${2:-$code}"
  # Structured denial on stderr; never print secrets.
  printf 'SSL_DENIAL code=%s message=%s\n' "$code" "$(soviez_redact_text "$msg")" >&2
  exit "${SOVIEZ_ERR_SSL:-7}"
}
