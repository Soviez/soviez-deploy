  shasum -a 256 "$OUT" | awk '{print $1}' > "$SUM"
elif command -v sha256sum >/dev/null 2>&1; then
  sha256sum "$OUT" | awk '{print $1}' > "$SUM"
else
  openssl dgst -sha256 "$OUT" | awk '{print $NF}' > "$SUM"
fi

echo "Built $OUT (version $VERSION)"
