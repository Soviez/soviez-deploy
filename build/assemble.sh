#!/usr/bin/env bash
# GENERATED FILE — do not edit. Built from soviez-sh/src by build/assemble.sh
# version: ${VERSION}
set -euo pipefail

HEADER

  for rel in "${MODULES[@]}"; do
    path="$SRC/$rel"
    if [[ ! -f "$path" ]]; then
      echo "Missing module: $path" >&2
      exit 1
    fi
    printf '# --- begin %s ---\n' "$rel"
    cat "$path"
    printf '\n# --- end %s ---\n\n' "$rel"
  done
} > "$OUT"

